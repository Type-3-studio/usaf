from __future__ import annotations

from datetime import UTC, datetime
from typing import Any

from pydantic import BaseModel, Field

from usaf.models.finding import Finding
from usaf.models.severity import CheckCategory, Severity


class CheckResult(BaseModel):
    check_id: str = Field(description="Check plugin ID")
    name: str = Field(description="Human-readable check name")
    category: CheckCategory = Field(description="Check category")
    passed: bool = Field(description="Whether the check passed")
    findings: list[Finding] = Field(
        default_factory=list, description="Findings generated by this check"
    )
    execution_time_ms: float = Field(default=0.0, description="Execution time in milliseconds")
    error: str | None = Field(default=None, description="Error message if check failed")
    warnings: list[str] = Field(default_factory=list, description="Warnings during execution")

    @property
    def finding_count(self) -> int:
        return len(self.findings)

    @property
    def max_severity(self) -> Severity | None:
        if not self.findings:
            return None
        return max(f.severity for f in self.findings)

    @property
    def max_risk_score(self) -> float:
        if not self.findings:
            return 0.0
        return max(f.risk_score for f in self.findings)

    def model_dump(self, **kwargs: Any) -> dict[str, Any]:
        return super().model_dump(exclude_none=True, **kwargs)


class ScanMetadata(BaseModel):
    scan_name: str = Field(default="usaf-scan", description="Name of this scan")
    scan_id: str = Field(default="", description="Unique scan identifier")
    start_time: datetime = Field(default_factory=lambda: datetime.now(UTC))
    end_time: datetime | None = Field(default=None)
    duration_seconds: float = Field(default=0.0)
    hostname: str = Field(default="")
    os_info: str = Field(default="")
    kernel_info: str = Field(default="")
    usaf_version: str = Field(default="")
    python_version: str = Field(default="")
    configuration_file: str | None = Field(default=None)
    total_checks: int = Field(default=0)
    enabled_checks: int = Field(default=0)
    collector_count: int = Field(default=0)
    errors: list[str] = Field(default_factory=list)

    def model_dump(self, **kwargs: Any) -> dict[str, Any]:
        return super().model_dump(exclude_none=True, **kwargs)


class ScanResult(BaseModel):
    metadata: ScanMetadata = Field(default_factory=ScanMetadata)
    results: list[CheckResult] = Field(default_factory=list)
    collectors_data: dict[str, dict[str, Any]] = Field(default_factory=dict)

    @property
    def total_findings(self) -> int:
        return sum(r.finding_count for r in self.results)

    @property
    def findings(self) -> list[Finding]:
        return [f for r in self.results for f in r.findings]

    @property
    def findings_by_severity(self) -> dict[Severity, list[Finding]]:
        result: dict[Severity, list[Finding]] = {s: [] for s in Severity}
        for f in self.findings:
            result[f.severity].append(f)
        return result

    @property
    def findings_by_category(self) -> dict[CheckCategory, list[Finding]]:
        result: dict[CheckCategory, list[Finding]] = {}
        for f in self.findings:
            result.setdefault(f.category, []).append(f)
        return result

    @property
    def passed_checks(self) -> list[CheckResult]:
        return [r for r in self.results if r.passed]

    @property
    def failed_checks(self) -> list[CheckResult]:
        return [r for r in self.results if not r.passed]

    @property
    def check_count(self) -> int:
        return len(self.results)

    @property
    def failed_count(self) -> int:
        return len(self.failed_checks)

    @property
    def passed_count(self) -> int:
        return len(self.passed_checks)

    def model_dump(self, **kwargs: Any) -> dict[str, Any]:
        return super().model_dump(exclude_none=True, **kwargs)
